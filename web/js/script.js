document.addEventListener('DOMContentLoaded', () => {
  // --- 1. МОБИЛЬНОЕ МЕНЮ ---
  const menuToggle = document.querySelector('.menu-toggle');
  const nav = document.querySelector('.primary-nav');
  menuToggle?.addEventListener('click', () => {
    const expanded = menuToggle.getAttribute('aria-expanded') === 'true';
    menuToggle.setAttribute('aria-expanded', String(!expanded));
    nav.classList.toggle('is-open', !expanded);
  });

  // --- 2. МОДАЛЬНЫЕ ОКНА (ОТКРЫТИЕ/ЗАКРЫТИЕ) ---
  const openModal = (modal) => modal?.classList.add('is-open');
  const closeModal = (modal) => modal?.classList.remove('is-open');
  
  document.querySelectorAll('.modal').forEach((modal) => {
    modal.addEventListener('click', (event) => {
      if (event.target === modal || event.target.closest('.modal-close')) closeModal(modal);
    });
  });
  document.querySelectorAll('.modal-close-action').forEach((button) => {
    button.addEventListener('click', () => closeModal(button.closest('.modal')));
  });
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') {
        document.querySelectorAll('.modal.is-open').forEach(closeModal);
        setFiltersOpen?.(false); // Закрываем фильтры по Esc
    }
  });

  // --- 3. КАРТОЧКИ ФИЛЬМОВ И ССЫЛКИ (АДАПТАЦИЯ ПОД YII2) ---
  document.querySelectorAll('.movie-card').forEach((card) => {
    card.addEventListener('click', (event) => {
      if (event.target.closest('button')) return;
      // Movie links are generated by Yii2 in the view.
    });
  });

  document.querySelectorAll('.review-button').forEach((button) => {
    button.addEventListener('click', () => {
      if (button.dataset.authRequired === 'true') return;
      const movieId = button.dataset.id || button.closest('[data-id]')?.dataset.id;
      const url = new URL(document.body.dataset.votesUrl, window.location.origin);
      if (movieId) url.searchParams.set('movie_id', movieId);
      window.location.href = url.toString();
    });
  });
  document.querySelector('.vote-button')?.addEventListener('click', () => {
    const button = document.querySelector('.vote-button');
    const url = new URL(document.body.dataset.votesUrl, window.location.origin);
    if (button.dataset.id) url.searchParams.set('movie_id', button.dataset.id);
    window.location.href = url.toString();
  });

  // --- 4. ИНТЕРАКТИВ (ИЗБРАННОЕ И ПРОСМОТРЕННОЕ) ---
  const csrfToken = document.querySelector('meta[name="csrf-token"]')?.content;
  const toggleUrl = document.body.dataset.userMovieToggleUrl;
  const toggleUserMovie = async (button) => {
    const movieId = button.dataset.id;
    const type = button.classList.contains('watched-button') ? 'watched' : 'favorite';
    if (!movieId || !csrfToken || !toggleUrl) {
      throw new Error('Не удалось подготовить запрос состояния фильма.');
    }

    const response = await fetch(toggleUrl, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/x-www-form-urlencoded; charset=UTF-8',
        'X-CSRF-Token': csrfToken,
        'X-Requested-With': 'XMLHttpRequest',
      },
      body: new URLSearchParams({
        movie_id: movieId,
        type,
        _csrf: csrfToken,
      }),
    });
    if (response.status === 401 || response.status === 403) {
      window.location.href = document.body.dataset.loginUrl || '/site/login';
      return null;
    }

    const result = await response.json();
    if (!response.ok || !result.success) {
      throw new Error(result.error || 'Не удалось сохранить состояние фильма.');
    }

    return { type, state: Boolean(result.state) };
  };

  document.querySelectorAll('.save-button, .watched-button').forEach((button) => {
    button.addEventListener('click', async (event) => {
      event.preventDefault();
      event.stopPropagation();
      button.disabled = true;
      try {
        const result = await toggleUserMovie(button);
        if (!result) return;
        const { type, state } = result;
        const icon = button.querySelector('i');
        if (type === 'favorite') {
          button.classList.toggle('active', state);
          button.setAttribute('aria-label', state ? 'Удалить из избранного' : 'Добавить в избранное');
          icon?.classList.toggle('fa-regular', !state);
          icon?.classList.toggle('fa-solid', state);
          if (!state && window.location.pathname.endsWith('/favorites')) {
            button.closest('.movie-card')?.remove();
          }
        } else {
          button.classList.toggle('watched-active', state);
          const watchedIcon = button.querySelector('i');
          if (watchedIcon) {
            watchedIcon.classList.toggle('fa-regular', !state);
            watchedIcon.classList.toggle('fa-solid', state);
            button.setAttribute('aria-label', state ? 'Отметить как непросмотренное' : 'Отметить как просмотренное');
          } else {
            button.innerHTML = state ? 'Просмотрено ✓' : 'Отметить как просмотренное';
          }
        }
      } catch (error) {
        console.error(error);
      } finally {
        button.disabled = false;
      }
    });
  });

  // --- 5. ТАБЫ И ЗВЕЗДОЧКИ ---
  document.querySelectorAll('.tab').forEach((tab) => {
    tab.addEventListener('click', () => {
      document.querySelectorAll('.tab').forEach((item) => {
        item.classList.toggle('is-active', item === tab);
        item.setAttribute('aria-selected', String(item === tab));
      });
      document.querySelectorAll('.tab-panel').forEach((panel) => {
        panel.hidden = panel.id !== tab.dataset.tab;
        panel.classList.toggle('is-active', panel.id === tab.dataset.tab);
      });
    });
  });

  document.querySelectorAll('.stars button').forEach((star, index, stars) => {
    if (star.closest('#review-modal')) return;
    star.addEventListener('click', () => stars.forEach((item, itemIndex) => {
      item.style.opacity = itemIndex <= index ? '1' : '.35';
    }));
  });

  document.querySelectorAll('.vote-stars button').forEach((star, index, stars) => {
    star.addEventListener('click', () => {
      const rating = Number(star.dataset.rating) || index + 1;
      const ratingInput = document.querySelector('#rating-value');
      if (ratingInput) ratingInput.value = String(rating);
      document.querySelector('#rating-error')?.setAttribute('hidden', '');
      stars.forEach((item, itemIndex) => item.classList.toggle('is-selected', itemIndex < rating));
    });
  });

  document.querySelector('.vote-form')?.addEventListener('submit', (event) => {
    const ratingInput = document.querySelector('#rating-value');
    const ratingError = document.querySelector('#rating-error');
    if (!ratingInput || !ratingInput.value || ratingInput.value === '0') {
      event.preventDefault();
      ratingError?.removeAttribute('hidden');
      ratingError?.scrollIntoView({ behavior: 'smooth', block: 'center' });
    } else {
      ratingError?.setAttribute('hidden', '');
    }
  });

  let activeReviewCard = null;
  document.querySelectorAll('.reviewed-card').forEach((card) => {
    const showReview = () => {
      if (card.id === 'trigger-all-reviews') return;
      if (card.closest('#all-reviews-modal')) return;
      const modal = document.querySelector('#review-modal');
      if (!modal) return;
      const title = modal.querySelector('#review-title');
      const movie = modal.querySelector('#review-movie');
      const poster = modal.querySelector('#review-poster');
      const comment = modal.querySelector('#review-comment');
      const modalStars = modal.querySelectorAll('.stars button');
      const deleteButton = modal.querySelector('#delete-review-button');
      const rating = parseInt(card.dataset.rating, 10) || 0;
      activeReviewCard = card;
      if (title) title.textContent = card.dataset.movie || '';
      if (movie) movie.textContent = 'Ваша оценка';
      if (poster) {
        poster.src = card.dataset.poster || '';
        poster.alt = card.dataset.movie || '';
      }
      if (comment) comment.textContent = card.dataset.comment || 'Комментарий не оставлен.';
      modalStars.forEach((star, index) => {
        star.classList.remove('is-selected');
        star.style.opacity = index < rating ? '1' : '.35';
        if (index < rating) {
          star.classList.add('is-selected');
        }
      });

      if (deleteButton) {
        const url = new URL(deleteButton.dataset.baseUrl || deleteButton.href, window.location.origin);
        url.searchParams.set('id', card.dataset.reviewId);
        deleteButton.href = url.toString();
      }
      openModal(modal);
    };
    card.addEventListener('click', showReview);
    card.addEventListener('keydown', (event) => {
      if (event.key === 'Enter' || event.key === ' ') {
        event.preventDefault();
        showReview();
      }
    });
  });

  const openAllReviews = () => openModal(document.querySelector('#all-reviews-modal'));
  document.querySelector('#trigger-all-reviews')?.addEventListener('click', openAllReviews);
  document.querySelector('#trigger-all-reviews')?.addEventListener('keydown', (event) => {
    if (event.key === 'Enter' || event.key === ' ') {
      event.preventDefault();
      openAllReviews();
    }
  });

  document.querySelector('.review-edit-button')?.addEventListener('click', () => {
    if (!activeReviewCard) return;
    const form = document.querySelector('.vote-form');
    const modal = document.querySelector('#review-modal');
    if (!form || !modal) return;

    const movieSelect = form.querySelector('[name="movie_id"]');
    const reviewIdInput = form.querySelector('#review-id');
    const ratingInput = form.querySelector('#rating-value');
    const commentInput = form.querySelector('[name="comment"]');
    const rating = Number(activeReviewCard.dataset.rating) || 5;
    if (movieSelect) movieSelect.value = activeReviewCard.dataset.movieId || '';
    if (movieSelect) {
      const selectedOption = movieSelect.querySelector(`option[value="${activeReviewCard.dataset.movieId}"]`);
      if (selectedOption) selectedOption.disabled = false;
    }
    if (reviewIdInput) reviewIdInput.value = activeReviewCard.dataset.reviewId || '';
    if (ratingInput) ratingInput.value = String(rating);
    if (commentInput) commentInput.value = activeReviewCard.dataset.comment || '';
    form.querySelectorAll('.vote-stars button').forEach((star, index) => {
      star.classList.toggle('is-selected', index < rating);
    });
    closeModal(modal);
    form.scrollIntoView({ behavior: 'smooth', block: 'start' });
  });

  // --- 6. ПОКАЗ ПАРОЛЯ ---
  document.querySelectorAll('.password-toggle').forEach((toggle) => {
    toggle.addEventListener('click', () => {
      const input = toggle.parentElement.querySelector('input');
      const visible = input.type === 'text';
      input.type = visible ? 'password' : 'text';
      toggle.textContent = visible ? '◉' : '◎';
    });
  });

  // --- 7. ФИЛЬТРЫ КАТАЛОГА ---
  const filterToggle = document.querySelector('.filter-toggle');
  const filterPanel = document.querySelector('.catalog-filters');
  const filterClose = document.querySelector('.filter-close');
  const setFiltersOpen = (open) => {
    if (!filterPanel || !filterToggle) return;
    filterPanel.classList.toggle('is-open', open);
    filterToggle.setAttribute('aria-expanded', String(open));
  };
  filterToggle?.addEventListener('click', () => setFiltersOpen(!filterPanel.classList.contains('is-open')));
  filterClose?.addEventListener('click', () => setFiltersOpen(false));

  // --- 8. МОДАЛКА ВЫХОДА И "МНЕ ПОВЕЗЕТ" ---
  const logoutModal = document.querySelector('#logout-modal');
  document.querySelector('.logout-button')?.addEventListener('click', () => openModal(logoutModal));

  const cards = [...document.querySelectorAll('.movie-card')];
  const pickRandomMovie = () => {
    const movie = cards[Math.floor(Math.random() * cards.length)];
    if (!movie) return;
    const title = movie.querySelector('h3')?.textContent || movie.dataset.title;
    const movieId = movie.dataset.id;
    const resultElement = document.querySelector('.lucky-result');
    if (resultElement) resultElement.textContent = title;
    const movieLink = document.querySelector('#lucky-modal .button-primary');
    if (movieLink && movieId) {
      const url = new URL(movieLink.href, window.location.origin);
      url.searchParams.set('id', movieId);
      movieLink.href = url.toString();
    }
    openModal(document.querySelector('#lucky-modal'));
  };
  document.querySelector('#lucky-button')?.addEventListener('click', pickRandomMovie);
  document.querySelector('#hero-lucky-button')?.addEventListener('click', pickRandomMovie);

  // ВАЖНО: Блоки с event.preventDefault() для форм (логин, регистрация, профиль) УДАЛЕНЫ.
  // Теперь Yii2 берет управление отправкой форм на себя!
});